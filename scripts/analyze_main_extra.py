"""EXPLORATORY analyses on the completed main study (written AFTER the primary analysis was seen; labelled as such in every table).
sigma_run from main-v1-t0-rep vs main-v1-t0 (same checkpoint, same prompt, independent run); H2 (high vs medium) and model contrasts; per task x class table;
no-change / harm / gain rates with the pre-set band 0.10; OOD; S3 vs 0 and vs gain_greedy; cluster-level bootstrap throughout."""
import json, sys
from pathlib import Path
import numpy as np, pandas as pd
ROOT = Path(__file__).resolve().parents[1]; sys.path.insert(0, str(ROOT))
from wsarena.analysis.metrics import load_runs
rng = np.random.default_rng(1)
man = {e["sha256"][:12]: e for e in json.loads((ROOT / "configs/tasks/ckpt_manifest.json").read_text())["entries"] if e["status"] == "built"}
def get(exp):
    d = load_runs(ROOT / "runs" / exp); d = d[d["status"].isin(["verified", "failed"])].copy()
    d["arm"] = d["run_id"].str.split("__").str[2]; d["ckpt_id"] = d["ckpt"].map(lambda c: man[c]["ckpt_id"]); d["level"] = d["ckpt_class"].map({"S1": "L2", "S2": "L2", "S3": "L3"}); return d
main, rep = get("main-v1-t0"), get("main-v1-t0-rep")
LLM = ["sonnet55-medium", "sonnet55-high", "opus55-medium", "opus55-high"]
base = pd.concat([load_runs(ROOT / "runs" / e) for e in ("baselines-v1", "baselines-gain-v1", "baselines-greedy-v1", "baselines-ctrl2-v1")])
base["arm"] = base["run_id"].str.split("__").str[2]; base["ckpt_id"] = base["ckpt"].map(lambda c: man.get(c, {}).get("ckpt_id")); base = base.dropna(subset=["ckpt_id"])
cl = set(main["ckpt_id"]); base = base[base["ckpt_id"].isin(cl)]
out = ["# Main study: exploratory supplement (generated by scripts/analyze_main_extra.py)", "", "*Everything below was written after the primary analysis had been seen; none of it is part of the pre-registered families.*", ""]

def boot(x, n=5000):
    x = np.asarray(x, float); b = [x[rng.integers(0, len(x), len(x))].mean() for _ in range(n)]; return x.mean(), np.percentile(b, 2.5), np.percentile(b, 97.5)
# 1 per task x class table
tab = main.groupby(["task_id", "ckpt_class", "arm"])["d_sr_id"].mean().unstack("arm")[LLM]
ctrl = base.groupby(["task_id", "ckpt_class", "arm"])["d_sr_id"].mean().unstack("arm")[["gain_greedy", "analytic_ridge", "oracle_restore"]]
t = tab.join(ctrl).round(3); out += ["## 1 Mean hidden-ID dSR per task x class (2 checkpoints per cell; controls on the same checkpoints)", "", t.to_markdown(), ""]
# 2 gain / no-change / harm rates
rows = []
for a in LLM:
    for lv in ("L2", "L3"):
        d = main[(main["arm"] == a) & (main["level"] == lv)]["d_sr_id"]
        rows.append([a, lv, len(d), (d >= 0.10).mean(), ((d > -0.10) & (d < 0.10)).mean(), (d <= -0.10).mean()])
out += ["## 2 Run-level outcome shares (band 0.10): gain / no distinguishable change / harm", "", pd.DataFrame(rows, columns=["arm", "level", "runs", "gain", "no change", "harm"]).round(2).to_markdown(index=False), ""]
# 3 S3 vs 0, vs gain_greedy
per = main.groupby(["arm", "ckpt_id", "level"])["d_sr_id"].mean().reset_index(); gb = base[base["arm"] == "gain_greedy"].groupby("ckpt_id")["d_sr_id"].mean()
rows = []
for a in LLM:
    d = per[(per["arm"] == a) & (per["level"] == "L3")].set_index("ckpt_id")["d_sr_id"]; m, lo, hi = boot(d); diff = (d - gb.reindex(d.index)).dropna(); m2, lo2, hi2 = boot(diff)
    rows.append([a, len(d), m, lo, hi, m2, lo2, hi2])
out += ["## 3 S3 (healthy, can still improve; 6 checkpoints): mean dSR, and minus gain_greedy", "", pd.DataFrame(rows, columns=["arm", "n", "dSR", "lo", "hi", "minus gain_greedy", "lo2", "hi2"]).round(3).to_markdown(index=False), ""]
# 4 H2 and model contrasts (cluster level, all 16)
pv = per.pivot_table(index="ckpt_id", columns="arm", values="d_sr_id")
rows = []
for name, a, b in (("Sonnet: high - medium", "sonnet55-high", "sonnet55-medium"), ("Opus: high - medium", "opus55-high", "opus55-medium"), ("medium: Opus - Sonnet", "opus55-medium", "sonnet55-medium"), ("high: Opus - Sonnet", "opus55-high", "sonnet55-high")):
    m, lo, hi = boot((pv[a] - pv[b]).dropna()); rows.append([name, len(pv), m, lo, hi])
out += ["## 4 Effort and model contrasts (all 16 checkpoints, paired)", "", pd.DataFrame(rows, columns=["contrast", "n", "mean", "lo", "hi"]).round(3).to_markdown(index=False), ""]
# 5 sigma_run
m2 = main[main["arm"].isin(["sonnet55-medium", "opus55-medium"])].set_index(["ckpt_id", "arm"])["d_sr_id"]; r2 = rep.set_index(["ckpt_id", "arm"])["d_sr_id"]
j = pd.concat([m2.rename("main"), r2.rename("rep")], axis=1).dropna(); j["diff"] = j["main"] - j["rep"]
sd = lambda x: float(np.sqrt((x ** 2).mean() / 2))
out += ["## 5 Run-to-run spread (same checkpoint, same arm, independent run)", "", f"pairs: {len(j)}; sigma_run (RMS diff / sqrt 2) = {sd(j['diff']):.3f}; Sonnet-med {sd(j[j.index.get_level_values(1)=='sonnet55-medium']['diff']):.3f}, Opus-med {sd(j[j.index.get_level_values(1)=='opus55-medium']['diff']):.3f}; share of pairs differing by >= 0.10: {(j['diff'].abs()>=0.10).mean():.2f}", "",
        j.round(3).reset_index().to_markdown(index=False), ""]
# 6 OOD
rows = [[a, lv, main[(main["arm"] == a) & (main["level"] == lv)]["d_sr_id"].mean(), main[(main["arm"] == a) & (main["level"] == lv)]["d_sr_ood"].mean()] for a in LLM for lv in ("L2", "L3")]
out += ["## 6 ID vs OOD dSR (means over runs)", "", pd.DataFrame(rows, columns=["arm", "level", "dSR ID", "dSR OOD"]).round(3).to_markdown(index=False), ""]
Path(ROOT / "reports/MAIN_EXTRA.md").write_text("\n".join(out)); print("\n".join(out))
