"""A3 (weight-reliance) and A4 (reparameterisation invariance) analysis from stored runs. CPU only, no model calls.
A4: PSI = |dSR(theta) - dSR(T(theta))| per (task, class, arm); same hidden episodes (function-preserving), so SR change differences reflect the editor only.
A3: WRI = dSR(full) - dSR(blind) per (checkpoint, arm) [positive = reading the weights helps]; shuffled arm: dSR(full) - dSR(shuffled).
Reference scale: run-to-run spread is NOT measured here (reps=1); we report |PSI| next to the decision band 0.10 and the ID noise floor 0.03."""
import json, glob, sys
from pathlib import Path
import numpy as np
ROOT = Path(__file__).resolve().parents[1]

def load(pattern):
    out = {}
    for f in glob.glob(str(ROOT / "runs" / pattern / "run.json")):
        j = json.load(open(f))
        if j.get("status") != "verified": continue
        out[j["spec"]["run_id"]] = j
    return out

def d(j, split="id"): return j["final"]["hidden"][split]["delta_sr"]

base = {}
for p in ("pilot-v0/a1/*", "pilot-v1/*/*"):
    base.update(load(p))
rows = ["| run | arm | dSR_ID orig | dSR_ID reparam | PSI_ID | dSR_OOD orig | dSR_OOD reparam | PSI_OOD |", "|---|---|---|---|---|---|---|---|"]
psi_id, psi_ood = [], []
for rid, j in sorted(load("a4-reparam-v1/*/*").items()):
    orig = base.get(rid.replace("-reparam", ""))
    if orig is None: rows.append(f"| {rid} | | no matching pilot run |"); continue
    a, b = d(orig), d(j); ao, bo = d(orig, "ood"), d(j, "ood"); psi_id.append(abs(a - b)); psi_ood.append(abs(ao - bo))
    rows.append(f"| {rid.split('__')[0]}/{rid.split('__')[1].replace('-reparam','')} | {rid.split('__')[2]} | {a:+.3f} | {b:+.3f} | {abs(a-b):.3f} | {ao:+.3f} | {bo:+.3f} | {abs(ao-bo):.3f} |")
txt = ["# A3/A4 analysis (generated by scripts/analyze_a3a4.py)", "", "## A4 reparameterisation invariance", ""] + rows
if psi_id: txt += ["", f"mean |PSI_ID| = {np.mean(psi_id):.3f}, median {np.median(psi_id):.3f}, max {np.max(psi_id):.3f}, n={len(psi_id)}; mean |PSI_OOD| = {np.mean(psi_ood):.3f}. Decision band 0.10; ID noise floor 0.03."]
for tag in ("blind", "shuffled"):
    runs = load(f"a3-{tag}-v1/*/*")
    if not runs: continue
    rows = [f"| run | arm | dSR_ID full | dSR_ID {tag} | WRI_ID | WRI_OOD |", "|---|---|---|---|---|---|"]; w = []
    for rid, j in sorted(runs.items()):
        key = rid.replace(f"-{tag}", "") if f"-{tag}" in rid else rid
        full = base.get(key)
        if full is None: continue
        wri = d(full) - d(j); w.append(wri)
        rows.append(f"| {rid.split('__')[0]}/{rid.split('__')[1]} | {rid.split('__')[2]} | {d(full):+.3f} | {d(j):+.3f} | {wri:+.3f} | {d(full,'ood') - d(j,'ood'):+.3f} |")
    txt += ["", f"## A3 {tag}", ""] + rows + ([f"", f"mean WRI_ID = {np.mean(w):+.3f}, n={len(w)}"] if w else [])
out = ROOT / "reports/A3_A4_ANALYSIS.md"; out.write_text("\n".join(txt) + "\n"); print("\n".join(txt))
