"""REVIEW-01 (Codex): C3 point estimate vs CI/p estimands. In analyze_main.py c3(), `diff` = pooled mean(L3 clusters) - mean(L2 clusters), while the bootstrap CI and the permutation p
are built on task-equal-weighted means (PREREG §11: 'task-stratified'). This script computes BOTH estimands with the SAME resampling scheme and reports the impact.
The frozen report is not changed; this is an amendment with version impact stated. usage: analyze_c3_check.py --llm EXP --out FILE"""
import argparse, json, sys
from pathlib import Path
import numpy as np, pandas as pd
ROOT = Path(__file__).resolve().parents[1]; sys.path.insert(0, str(ROOT))
from wsarena.analysis.metrics import load_runs
ap = argparse.ArgumentParser(); ap.add_argument("--llm", required=True); ap.add_argument("--out", required=True); ap.add_argument("--seeds", default="2,3"); a = ap.parse_args()
man = {e["sha256"][:12]: e for e in json.loads((ROOT / "configs/tasks/ckpt_manifest.json").read_text())["entries"] if e["status"] == "built"}
d = load_runs(ROOT / "runs" / a.llm); d = d[d["status"].isin(["verified", "failed"])].copy()
d["arm"] = d["run_id"].str.split("__").str[2]; d["ckpt_id"] = d["ckpt"].map(lambda c: man[c]["ckpt_id"]); d["seed"] = d["ckpt"].map(lambda c: man[c]["seed"])
d = d[d["seed"].isin({int(s) for s in a.seeds.split(",")})]; d["level"] = d["ckpt_class"].map({"S1": "L2", "S2": "L2", "S3": "L3"})
per = d.groupby(["arm", "task_id", "ckpt_id", "level"])["d_sr_id"].mean().reset_index()
rng = np.random.default_rng(0); NB = 5000

def est(df, kind):
    if kind == "pooled": return df[df.level == "L3"].d_sr_id.mean() - df[df.level == "L2"].d_sr_id.mean()
    t = [df[(df.task_id == k) & (df.level == "L3")].d_sr_id.mean() - df[(df.task_id == k) & (df.level == "L2")].d_sr_id.mean() for k in df.task_id.unique()]
    return float(np.nanmean(t))

rows = []
for arm, g in per.groupby("arm"):
    g = g.reset_index(drop=True); obs = {k: est(g, k) for k in ("pooled", "taskw")}
    cells = {k: v.d_sr_id.to_numpy() for k, v in g.groupby(["task_id", "level"])}
    out = {"arm": arm, "n_L3": int((g.level == "L3").sum()), "n_L2": int((g.level == "L2").sum()), **{f"obs_{k}": v for k, v in obs.items()}}
    for kind in ("pooled", "taskw"):
        bs = []
        for _ in range(NB):                     # resample clusters within each task x level cell (same scheme for both estimands)
            parts = []
            for (t, lv), x in cells.items(): parts += [pd.DataFrame({"task_id": t, "level": lv, "d_sr_id": x[rng.integers(0, len(x), len(x))]})]
            bs.append(est(pd.concat(parts), kind))
        bs = np.array(bs); out[f"ci_{kind}"] = (float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5)))
        tk = g.task_id.to_numpy(); lab = (g.level == "L3").to_numpy().astype(int); cnt = 0
        for _ in range(NB):                     # permute level labels within each task (null: no L3/L2 difference)
            pl = lab.copy()
            for t in set(tk): ix = np.where(tk == t)[0]; pl[ix] = rng.permutation(pl[ix])
            gg = g.assign(level=np.where(pl == 1, "L3", "L2")); cnt += abs(est(gg, kind)) >= abs(obs[kind]) - 1e-12
        out[f"p_{kind}"] = (cnt + 1) / (NB + 1)
    rows.append(out)
t = ["# C3 estimand check (REVIEW-01) — generated by scripts/analyze_c3_check.py", "", f"experiment `{a.llm}`; seeds {a.seeds}. `pooled` = mean over L3 clusters − mean over L2 clusters (what analyze_main.py printed as the point estimate); `task-weighted` = mean over tasks of the within-task difference (what its CI and p were built on, and what PREREG §11 calls task-stratified). Same resampling and permutation scheme for both.", "",
     "| arm | n L3 / n L2 | pooled diff | pooled 95% CI | pooled p | task-weighted diff | task-weighted 95% CI | task-weighted p |", "|---|---|---|---|---|---|---|---|"]
for r in rows:
    t.append(f"| {r['arm']} | {r['n_L3']} / {r['n_L2']} | {r['obs_pooled']:+.3f} | [{r['ci_pooled'][0]:+.3f}, {r['ci_pooled'][1]:+.3f}] | {r['p_pooled']:.4f} | {r['obs_taskw']:+.3f} | [{r['ci_taskw'][0]:+.3f}, {r['ci_taskw'][1]:+.3f}] | {r['p_taskw']:.4f} |")
Path(a.out).write_text("\n".join(t) + "\n"); print("\n".join(t))
